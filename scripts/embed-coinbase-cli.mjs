import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = resolve(
  projectRoot,
  "node_modules",
  "@coinbase",
  "coinbase-cli",
);
const outputPath = resolve(
  projectRoot,
  "agent",
  "lib",
  "coinbase-cli-source.generated.ts",
);

const [metadataText, source, license] = await Promise.all([
  readFile(resolve(packageRoot, "package.json"), "utf8"),
  readFile(resolve(packageRoot, "dist", "index.js"), "utf8"),
  readFile(resolve(packageRoot, "LICENSE"), "utf8"),
]);
const metadata = JSON.parse(metadataText);

if (
  metadata.name !== "@coinbase/coinbase-cli" ||
  typeof metadata.version !== "string" ||
  !source.startsWith("#!/usr/bin/env node") ||
  !source.includes("coinbase mcp") ||
  metadata.license !== "MIT" ||
  !license.includes("Copyright (c) 2026 Coinbase") ||
  license.includes("*/")
) {
  throw new Error("The installed Coinbase CLI package has an unexpected shape.");
}

// Retain the upstream notice in the executable itself, including after bundling.
const shebangEnd = source.indexOf("\n") + 1;
const licensedSource = `${source.slice(0, shebangEnd)}/*!\n${license.trim()}\n*/\n${source.slice(shebangEnd)}`;
const sha256 = createHash("sha256").update(licensedSource).digest("hex");
const generated = `// Generated by scripts/embed-coinbase-cli.mjs. Do not edit.
export const coinbaseCliSource = ${JSON.stringify(licensedSource)};
export const coinbaseCliVersion = ${JSON.stringify(metadata.version)};
export const coinbaseCliSha256 = ${JSON.stringify(sha256)};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, "utf8");
